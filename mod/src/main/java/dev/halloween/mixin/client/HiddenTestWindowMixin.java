package dev.halloween.mixin.client;
import net.minecraft.client.util.Window;
import org.lwjgl.glfw.GLFW;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.*;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfo;
/** Development tests can render off-screen without stealing the user's gameplay window. */
@Mixin(Window.class)
public abstract class HiddenTestWindowMixin {
 @Inject(method="<init>",at=@At(value="INVOKE",target="Lorg/lwjgl/glfw/GLFW;glfwCreateWindow(IILjava/lang/CharSequence;JJ)J"))
 private void hiddenTest(CallbackInfo ci){if(Boolean.getBoolean("halloween.hiddenClientTest")&&net.fabricmc.loader.api.FabricLoader.getInstance().isDevelopmentEnvironment()){GLFW.glfwWindowHint(GLFW.GLFW_VISIBLE,GLFW.GLFW_FALSE);GLFW.glfwWindowHint(GLFW.GLFW_FOCUSED,GLFW.GLFW_FALSE);GLFW.glfwWindowHint(GLFW.GLFW_FOCUS_ON_SHOW,GLFW.GLFW_FALSE);}}
}
